"""Assemble the training matrix and attach programmatic weak labels.

No labelled dataset of "this thermal anomaly was a refinery flare" exists, so
labels are generated by rules over independent evidence -- persistence, OSM
infrastructure, land cover, and NASA's own static-source flag. Each rule encodes
a claim a domain expert would accept:

  thermal_power      persistent + sitting on a known thermal power station
  gas_flare          persistent + oil/gas or refinery context + burns at night
  mining             on a quarry/coal polygon (persistent or not)
  industrial_fire    TRANSIENT heat inside an industrial footprint -- an event,
                     not a routine process. This is the accident class.
  agricultural_burn  transient + cropland + daytime + harvest season
  wildfire           transient + tree cover + far from any industry

Rules are applied most-specific first and a detection keeps the first label it
matches. Detections matching nothing stay unlabelled and are excluded from
training -- that is expected and healthy; the classifier's job is to generalise
to them.

Every label carries `label_confidence` so training can down-weight the rules
that lean on weaker evidence.

Usage:
    python -m src.model.dataset
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from config import INTERIM, PROCESSED  # noqa: E402

# Rabi/kharif residue burning peaks: Oct-Nov (paddy) and Apr-May (wheat).
HARVEST_MONTHS = {4, 5, 10, 11}


def _shrink(df: pd.DataFrame) -> pd.DataFrame:
    """Downcast floats to 32-bit before joining.

    Cell-level tables get broadcast across every detection in the cell, so a
    float64 column here costs ~21 MB per column at 2.66 M rows. Halving that
    keeps the joined frame on a laptop.
    """
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].astype(np.float32)
    return df


def load_and_join(interim: Path, processed: Path) -> pd.DataFrame:
    """Join detection-level records to their cell-level feature tables."""
    det = pd.read_parquet(interim / "firms_gridded.parquet")
    print(f"detections      : {len(det):,}")

    cells = pd.read_parquet(processed / "cells.parquet")
    keep_cell = [
        "cell_id", "n_detections", "n_active_days", "n_months", "night_ratio",
        "month_entropy", "peak_month_share", "duty_cycle", "coverage_of_record",
        "lifetime_days", "spread_m", "frp_mean", "frp_std", "frp_cv", "frp_p95",
        "ti4_mean", "ti4_std", "ti4_ti5_diff", "is_persistent",
        "firms_type0_frac", "firms_type2_frac", "firms_type3_frac",
    ]
    cells = _shrink(cells[[c for c in keep_cell if c in cells.columns]])
    df = det.merge(cells, on="cell_id", how="left", suffixes=("", "_cell"))
    print(f"+ cell features : {df.shape[1]} cols")

    ctx_path = interim / "context.parquet"
    if ctx_path.exists():
        df = df.merge(_shrink(pd.read_parquet(ctx_path)), on="cell_id", how="left")
        print(f"+ context       : {df.shape[1]} cols")
    else:
        print("  [warn] context.parquet missing -- spatial features skipped")

    lc_path = interim / "landcover.parquet"
    if lc_path.exists():
        df = df.merge(_shrink(pd.read_parquet(lc_path)), on="cell_id", how="left")
        print(f"+ landcover     : {df.shape[1]} cols")
    else:
        print("  [warn] landcover.parquet missing -- land cover features skipped")

    return df


def add_detection_features(df: pd.DataFrame) -> pd.DataFrame:
    """Per-detection radiometric and temporal features."""
    df = df.copy()
    df["ti4_ti5"] = df["bright_ti4"] - df["bright_ti5"]
    df["is_night"] = df["daynight"].eq("N").astype(np.int8)

    dt = pd.to_datetime(df["acq_date"])
    df["month"] = dt.dt.month.astype(np.int8)
    df["doy"] = dt.dt.dayofyear.astype(np.int16)
    # Cyclic encoding so December and January sit next to each other.
    df["doy_sin"] = np.sin(2 * np.pi * df["doy"] / 365.25)
    df["doy_cos"] = np.cos(2 * np.pi * df["doy"] / 365.25)

    if "confidence" in df.columns:
        df["conf_rank"] = df["confidence"].map({"l": 0, "n": 1, "h": 2}).fillna(1)

    return df


def _col(df: pd.DataFrame, name: str, default: float) -> pd.Series:
    """Fetch a feature column, or a constant if that feature was not built."""
    if name in df.columns:
        return df[name].fillna(default)
    return pd.Series(default, index=df.index, dtype="float64")


def assign_weak_labels(df: pd.DataFrame) -> pd.DataFrame:
    """Apply the rule cascade. First matching rule wins."""
    df = df.copy()
    df["weak_label"] = pd.NA
    df["label_confidence"] = np.nan

    persistent = _col(df, "is_persistent", 0).astype(bool)
    night_ratio = _col(df, "night_ratio", 0.0)
    type2 = _col(df, "firms_type2_frac", 0.0)

    d_plant = _col(df, "dist_thermal_plant_km", 999.0)
    d_ref = _col(df, "dist_refinery_km", 999.0)
    d_oil = _col(df, "dist_oil_gas_km", 999.0)
    d_flare = _col(df, "dist_flare_km", 999.0)
    d_mine = _col(df, "dist_mining_km", 999.0)
    d_ind = _col(df, "dist_any_industry_km", 999.0)

    in_ind = _col(df, "inside_industrial", 0).astype(bool)
    in_mine = _col(df, "inside_mining", 0).astype(bool)

    crop = _col(df, "lc_crop_1km", 0.0)
    tree = _col(df, "lc_tree_1km", 0.0)

    is_day = df["daynight"].eq("D")
    harvest = df["month"].isin(HARVEST_MONTHS)

    # Order matters: the first matching rule wins, so the most *specific*
    # evidence must come first. An earlier version put the generic "NASA says
    # static source" gas_flare rule above mining, which relabelled the entire
    # Jharia coal seam fire as a gas flare; and thermal_power demanded a plant
    # within 2 km when detections routinely sit 3-5 km from the plant centroid,
    # so Korba and Singrauli fell through to mining.
    rules = [
        (
            # A named power station nearby is strong, specific evidence.
            "thermal_power",
            persistent & (d_plant < 4.0),
            0.90,
        ),
        (
            # Sitting inside a mapped quarry/coalfield polygon is unambiguous.
            "mining",
            in_mine | (d_mine < 1.0),
            0.85,
        ),
        (
            "gas_flare",
            persistent
            & ((d_ref < 3.0) | (d_oil < 3.0) | (d_flare < 3.0))
            & (night_ratio > 0.5),
            0.85,
        ),
        (
            # Persistent heavy industry that is not a flare, plant or mine:
            # steel, aluminium, cement, chemicals. Without this class every
            # smelter was forced into gas_flare.
            "industrial_plant",
            persistent & (in_ind | (d_ind < 2.0)) & (night_ratio > 0.4),
            0.70,
        ),
        (
            # Last resort for persistent sources: NASA flags it static and there
            # is industry nearby, but we cannot pin the facility type.
            "gas_flare",
            persistent & (type2 > 0.8) & (d_ind < 3.0) & (night_ratio > 0.7),
            0.60,
        ),
        (
            "industrial_fire",
            ~persistent & (in_ind | (d_ind < 1.0)),
            0.70,
        ),
        (
            "agricultural_burn",
            ~persistent & (crop > 0.5) & is_day & harvest & (d_ind > 3.0),
            0.85,
        ),
        (
            "wildfire",
            ~persistent & (tree > 0.3) & (d_ind > 5.0) & (d_mine > 5.0),
            0.80,
        ),
    ]

    for label, mask, conf in rules:
        take = mask & df["weak_label"].isna()
        df.loc[take, "weak_label"] = label
        df.loc[take, "label_confidence"] = conf
        print(f"  {label:20s} +{int(take.sum()):>9,}  (conf {conf})")

    return df


def main() -> None:
    ap = argparse.ArgumentParser(description="Assemble dataset and weak labels")
    ap.add_argument("--out", default=str(PROCESSED / "training_data.parquet"))
    args = ap.parse_args()

    df = load_and_join(INTERIM, PROCESSED)
    df = add_detection_features(df)

    print("\napplying weak label rules:")
    df = assign_weak_labels(df)

    labelled = df["weak_label"].notna()
    print(f"\nlabelled {int(labelled.sum()):,} of {len(df):,} "
          f"({100 * labelled.mean():.1f}%)")
    print("\nclass balance:")
    vc = df.loc[labelled, "weak_label"].value_counts()
    for cls, n in vc.items():
        print(f"  {cls:20s} {n:>9,}  {100 * n / labelled.sum():5.1f}%")

    out_path = Path(args.out)
    df.to_parquet(out_path, index=False)
    print(f"\nwrote {df.shape[0]:,} x {df.shape[1]} -> {out_path}")
    print(f"size: {out_path.stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
